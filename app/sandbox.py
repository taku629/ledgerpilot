"""Sandbox execution + Tier-1 draft generation.

The sandbox is a simulated ledger — nothing here touches real money. Tier-2
actions mutate `sandbox_state.json` only after a consumed approval token.
Drafts (Tier-1) produce text artifacts; they change no state.
"""
from __future__ import annotations

import json
import time
from datetime import date
from pathlib import Path

import pandas as pd

from .config import DATA_DATE, DATA_DIR
from .security import mask_pii

STATE_PATH = DATA_DIR / "sandbox_state.json"


def _load_state() -> dict:
    if STATE_PATH.exists():
        return json.loads(STATE_PATH.read_text())
    return {"rescheduled_payments": {}, "executed": [], "cash_buffer_override": None}


def _save_state(s: dict):
    STATE_PATH.parent.mkdir(parents=True, exist_ok=True)
    STATE_PATH.write_text(json.dumps(s, indent=2))


def get_state() -> dict:
    return _load_state()


def apply_reschedules(sched: pd.DataFrame) -> pd.DataFrame:
    """Overlay user-approved reschedules onto the payment calendar."""
    s = _load_state()["rescheduled_payments"]
    sched = sched.copy()
    for pid, new_date in s.items():
        sched.loc[sched.id == pid, "next_date"] = new_date
    return sched


# ------------------------------------------------------------ Tier-2 actions
def validate_reschedule_date(new_date: str) -> str | None:
    """Returns an error string when a reschedule target is out of range,
    else None — shared by the proposal path and the executor."""
    try:
        nd = pd.Timestamp(new_date)
    except Exception:
        return f"invalid date {new_date}"
    today = pd.Timestamp(DATA_DATE or date.today())
    if nd.date() < today.date():
        return f"{new_date} is in the past — pick a future date"
    if nd > today + pd.Timedelta(weeks=104):
        return f"{new_date} is over 2 years out — pick a nearer date"
    return None


def exec_reschedule_payment(sched: pd.DataFrame, payment_id: str,
                            new_date: str) -> dict:
    row = sched[sched.id == payment_id]
    if row.empty:
        return {"ok": False, "error": f"unknown payment_id {payment_id}"}
    old = row.iloc[0].next_date
    err = validate_reschedule_date(new_date)
    if err:
        return {"ok": False, "error": err}
    if str(old) == new_date:
        return {"ok": False,
                "error": f"{payment_id} is already scheduled on {new_date}"}
    s = _load_state()
    s["rescheduled_payments"][payment_id] = new_date
    _save_state(s)
    return {"ok": True, "payment_id": payment_id, "old_date": old,
            "new_date": new_date, "category": row.iloc[0].category,
            "amount": float(row.iloc[0].amount)}


def exec_set_cash_buffer(amount: float) -> dict:
    s = _load_state()
    s["cash_buffer_override"] = float(amount)
    _save_state(s)
    return {"ok": True, "cash_buffer": float(amount)}


def exec_record_sandbox_wire(params: dict) -> dict:
    """Simulated outbound payment. Recorded in the sandbox ledger only."""
    s = _load_state()
    entry = {"ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
             "kind": "sandbox_wire", **mask_pii(params)}
    s["executed"].append(entry)
    _save_state(s)
    return {"ok": True, "recorded": entry, "note": "simulated ledger entry only"}


# ------------------------------------------------------------- Tier-1 drafts
def draft_dunning_email(invoice: dict, business: str) -> dict:
    days_late = (pd.Timestamp.today().normalize()
                 - pd.Timestamp(invoice["due_date"])).days
    subject = f"Payment reminder — invoice {invoice['id']} ({days_late}d past due)"
    body = (
        f"Dear {invoice['customer']} team,\n\n"
        f"I hope you are well. Our records show invoice {invoice['id']} for "
        f"${invoice['amount']:,.2f}, dated {invoice['issue_date']}, was due on "
        f"{invoice['due_date']} and remains unpaid ({days_late} days past due).\n\n"
        f"Could you confirm the payment date? If there is an issue with the "
        f"invoice, please let me know and I will resolve it right away.\n\n"
        f"Thank you,\n{business}\n\n"
        f"---\nDraft generated by LedgerPilot. Review before sending."
    )
    return {"type": "dunning_email", "invoice_id": invoice["id"],
            "to": mask_pii(invoice.get("customer", "")), "subject": subject,
            "body": body, "status": "draft"}


def draft_loan_application(product: dict, profile: dict, gap: dict) -> dict:
    body = (
        f"LOAN APPLICATION DRAFT — {product['name']}\n"
        f"{'=' * 52}\n"
        f"Business:        {profile['business_name']}\n"
        f"Founded:         {profile['founded']} ({profile['months_operating']} months operating)\n"
        f"Avg monthly rev: ${profile['avg_monthly_revenue']:,.0f}\n"
        f"Current balance: ${profile['current_balance']:,.0f}\n\n"
        f"Requested amount: ${gap['gap_amount']:,.0f}\n"
        f"Purpose: cover projected cash-flow shortfall "
        f"(week {gap.get('gap_week', 'n/a')} of 13-week forecast)\n"
        f"Product terms:  est. cost ${product.get('est_total_cost', 0):,.0f}; "
        f"funds in ~{product['time_to_fund_days']} days\n\n"
        f"Repayment source: forecast POS + online + wholesale collections.\n\n"
        f"---\nDraft generated by LedgerPilot. Verify all figures with the lender's "
        f"official application form. This is not a submitted application."
    )
    return {"type": "loan_application", "product_id": product["id"],
            "product_name": product["name"], "body": body, "status": "draft"}
